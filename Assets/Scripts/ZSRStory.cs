        internal readonly struct Beat
        {
            internal readonly string Title, Max, Eva, After;

            internal Beat(string title, string max, string eva, string after)
            {
                Title = title;
                Max = max;
                Eva = eva;
                After = after;
            }

            internal string Line(int speaker) => speaker == 0 ? Max : Eva;
        }

        // The first arc ends at 15, the second runs for another 50 levels.
        // Later transmissions occur at 90, 115, 140, …, 990.
        internal static int IndexForLevel(int level)
        {
            if (level >= 5 && level <= 15 && level % 5 == 0) return level / 5 - 1;
            if (level > 15 && level <= 65 && (level - 15) % 10 == 0) return 2 + (level - 15) / 10;
            if (level > 65 && level <= ZSRLevelPlan.Count && (level - 65) % 25 == 0) return 7 + (level - 65) / 25;
            return -1;
        }

        internal static int SpeakerAt(float elapsed) =>
            elapsed < 1.4f || elapsed >= 20.4f ? -1 : elapsed < 10.9f ? 0 : 1;

        internal static bool TryGet(int level, out Beat beat)
        {
            int index = IndexForLevel(level);
            beat = index >= 0 ? Beats[index] : default;
            return index >= 0;
        }

