"""Build the four street profiles in both wear variants for the facade atlas."""

from pathlib import Path


MESHES = Path(__file__).resolve().parents[2] / "Assets" / "Resources" / "Meshes"
ATLAS = 1024
TILE = 256
UV_INSET = 12


class Building:
    def __init__(self, profile, wear):
        self.profile = profile
        self.front = profile * 2 + wear
        self.side = profile * 2 + 1 - wear
        self.vertices = []
        self.uvs = []
        self.faces = []

    def face(self, points, tile):
        first = len(self.vertices) + 1
        self.vertices.extend(points)
        left = (tile % 4 * TILE + UV_INSET) / ATLAS
        right = ((tile % 4 + 1) * TILE - UV_INSET) / ATLAS
        top = 1 - (tile // 4 * TILE + UV_INSET) / ATLAS
        bottom = 1 - ((tile // 4 + 1) * TILE - UV_INSET) / ATLAS
        corners = [(left, bottom), (left, top), (right, top), (right, bottom)]
        if len(points) == 4:
            self.uvs.extend(corners)
        else:
            # Roof coverage is plan-mapped across its atlas tile.
            min_x, max_x = min(p[0] for p in points), max(p[0] for p in points)
            min_z, max_z = min(p[2] for p in points), max(p[2] for p in points)
            self.uvs.extend(
                (left + (right - left) * (x - min_x) / (max_x - min_x),
                 bottom + (top - bottom) * (z - min_z) / (max_z - min_z))
                for x, _, z in points
            )
        self.faces.extend((first, first + i, first + i + 1) for i in range(1, len(points) - 1))

    def wing(self, x, z, bottom, top, width, depth, tile, bevel=0):
        a, b = x - width / 2, x + width / 2
        c, d = z - depth / 2, z + depth / 2
        ring = [(a, c), (b, c), (b, d), (a, d)]
        if bevel:
            ring = [(a + bevel, c), (b - bevel, c), (b, c + bevel), (b, d - bevel),
                    (b - bevel, d), (a + bevel, d), (a, d - bevel), (a, c + bevel)]
        lower = [(u, bottom, v) for u, v in ring]
        upper = [(u, top, v) for u, v in ring]
        for i in range(len(ring)):
            j = (i + 1) % len(ring)
            facade = tile
            if tile == self.front:
                if bevel and i % 2:
                    facade = 8
                elif i in (1, 3) or (bevel and i in (2, 6)):
                    facade = self.side
            self.face([lower[i], upper[i], upper[j], lower[j]], facade)
        self.face(list(reversed(upper)), 9)
        self.face(lower, 10)

    def save(self, wear):
        out = MESHES / f"zsr_city_{self.profile}_{wear}.obj"
        lines = ["# Generated by Tools/Art/build_city_meshes.py", f"o City_{self.profile}_{wear}", "s off"]
        lines += [f"v {x:.6f} {y:.6f} {z:.6f}" for x, y, z in self.vertices]
        lines += [f"vt {u:.7f} {v:.7f}" for u, v in self.uvs]
        lines += ["f " + " ".join(f"{i}/{i}" for i in face) for face in self.faces]
        out.write_text("\n".join(lines) + "\n", encoding="ascii")
        return len(self.faces)


def build(profile, wear):
    b = Building(profile, wear)
    front = b.front
    b.wing(0, 0, 0, .13, 1.00, .96, 10, .06)

    if profile == 0:
        # Stone office podium, glazed shaft and a setback mechanical roof.
        b.wing(-.05, .04, .12, .89, .84, .80, front, .04)
        b.wing(-.05, .04, .80, .823, .88, .84, 8, .04)
        b.wing(-.05, .04, .88, .902, .885, .85, 8, .04)
        b.wing(-.12, .15, .90, .985, .53, .52, front, .025)
        b.wing(.18, .08, .89, .944, .22, .34, 11)
        b.wing(-.21, .19, .978, 1.13, .034, .032, 9)
    elif profile == 1:
        # Brick hotel, offset service core and staggered terracotta cornices.
        b.wing(.105, .04, .12, .80, .73, .83, front, .032)
        b.wing(-.33, -.15, .12, .64, .29, .60, front)
        b.wing(.105, .04, .785, .814, .78, .89, 8, .032)
        b.wing(.067, .11, .81, .935, .59, .62, front)
        b.wing(.067, .11, .925, .95, .64, .67, 11)
        b.wing(-.10, .17, .94, 1.04, .20, .23, 11)
        b.wing(.325, .26, .81, .865, .10, .15, 9)
    elif profile == 2:
        # Broken concrete apartments. Exposed shoulders and interrupted slabs.
        b.wing(-.075, .03, .12, .70, .82, .83, front, .02)
        b.wing(.28, .07, .17, .60, .38, .65, front)
        b.wing(-.13, .09, .69, .90, .62, .69, front)
        b.wing(-.19, .18, .89, .985, .48, .48, 10)
        b.wing(-.31, .15, .975, 1.065, .16, .32, front)
        for i in range(3):
            y = .26 + .17 * i
            b.wing(-.07, -.375, y, y + .026, .86 - .11 * i, .16, 8)
        b.wing(.065, .19, .902, .967, .03, .03, 11)
    else:
        # Tapered glass landmark with a split crown and a vertical service spine.
        b.wing(-.045, .044, .12, .84, .84, .80, front, .112)
        b.wing(.346, .12, .17, .72, .17, .43, 9, .04)
        b.wing(-.105, .084, .835, 1.02, .69, .68, front, .08)
        b.wing(-.17, .12, 1.012, 1.112, .53, .48, 9, .052)
        b.wing(-.06, .18, 1.10, 1.22, .032, .03, 11)
        b.wing(.08, .23, 1.10, 1.18, .024, .024, 11)
    # Recessed floor edges, service balconies and roof equipment share the facade atlas.
    if profile in (1,2):
        for floor in range(4):
            y=.20+floor*.14
            for side in (-1,1):
                x=side*.32
                b.wing(x,-.43,y,y+.012,.21,.12,8,.008)
                b.wing(x,-.478,y+.012,y+.044,.21,.016,9,.004)
    for unit in range(2):
        x=-.17+unit*.24
        b.wing(x,.04,.98,1.035,.15,.17,11,.015)
        b.wing(x,-.049,1.005,1.023,.11,.018,8,.006)
    b.wing(.36,.26,.14,.84,.024,.025,9,.005)
    return b.save(wear)


if __name__ == "__main__":
    for profile in range(4):
        for wear in range(2):
            print(f"city {profile}/{wear}: {build(profile, wear)} triangles")
